#!/usr/bin/env python3
"""Writes firmware/src/rs_mix_tables.h: the constants and tables of the C mix (rs_mix.c), worked out here in float
from what the HTML's chain is in Chromium (tools/tone-ref/probe_mix.mjs measures each piece):

  bot B's low-pass   Tone.Filter lowpass 1400 Hz, -12: one Web Audio biquad, Q 1 (dB): its coefficients, Q30
  the hall reverb    Tone.Reverb decay 1.2, preDelay .01: a convolver with white noise under exp(-t / tau),
                     tau = ln(2.2) / ln(200) s (Tone's exponentialApproachValueAtTime), normalized by Chromium to
                     0.00125893^2 * 53361 of energy a channel. Here an 8-line feedback delay network after four
                     diffusing all-passes, each line's gain exp(-length / tau): the same decay, the same energy
  the limiter        Tone.Limiter(-6): Chromium's DynamicsCompressorKernel (compressor.py), its curve and rates
                     as tables

  python3 tools/tone-ref/mix_tables.py [--check]     (--check: fails when the header differs from what it would write)"""
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from compressor import Curve, SR, SAT_RELEASE, ZONES, SPACING_DB, PRE_DELAY  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "firmware" / "src" / "rs_mix_tables.h"
Q30 = 1 << 30

# ---- the reverb's design
TAU = math.log(2.2) / math.log(200) * SR                # samples
PRE = int(round(0.01 * SR))
LINES = [601, 709, 797, 887, 977, 1061, 1151, 1249]     # primes: 7432 samples, a mode every ~6 Hz
SIGNS = [1, -1, 1, -1, -1, 1, -1, 1]
APS = [89, 131, 197, 263]
AP_G = 0.6
DIRECT = 3.625                                          # the diffused input, straight out: the first 25 ms
ENERGY = 0.00125893 ** 2 * round(1.21 * SR)             # Chromium's normalized impulse response, a channel


def fdn_ir(n):
    """the network's impulse response in float, unscaled (rs_mix.c's structure)"""
    g = [math.exp(-d / TAU) / math.sqrt(8) for d in LINES]
    lines = [np.zeros(d) for d in LINES]
    li = [0] * 8
    aps = [np.zeros(d) for d in APS]
    ai = [0] * 4
    y = np.zeros(n)
    for t in range(n):
        s = 1.0 if t == 0 else 0.0
        for k, d in enumerate(APS):
            v = aps[k][ai[k]]
            w = s + AP_G * v
            aps[k][ai[k]] = w
            ai[k] = (ai[k] + 1) % d
            s = v - AP_G * w
        r = [lines[i][li[i]] for i in range(8)]
        y[t] = sum(SIGNS[i] * r[i] for i in range(8)) + DIRECT * s
        m = list(r)
        h = 1
        while h < 8:                                    # the fast Walsh-Hadamard transform
            for i in range(0, 8, 2 * h):
                for j in range(i, i + h):
                    m[j], m[j + h] = m[j] + m[j + h], m[j] - m[j + h]
            h *= 2
        for i in range(8):
            lines[i][li[i]] = g[i] * m[i] + s
            li[i] = (li[i] + 1) % LINES[i]
    return y


def q(x, bits=30):
    return int(round(x * (1 << bits)))


def table(name, ctype, values, per_line=8):
    rows = [", ".join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n    " + ",\n    ".join(rows) + "};\n"


def build():
    out = []
    p = out.append
    p("/* SPDX-License-Identifier: GPL-3.0-only */\n")
    p("/* Generated by tools/tone-ref/mix_tables.py: don't edit (it says where each number comes from). */\n")
    p("#ifndef RS_MIX_TABLES_H\n#define RS_MIX_TABLES_H\n#include <stdint.h>\n\n")

    # bot B's low-pass: Web Audio's lowpass biquad, Q in dB
    w0 = 2 * math.pi * 1400 / SR
    al = math.sin(w0) / (2 * 10 ** (1 / 20))
    c = math.cos(w0)
    a0 = 1 + al
    b0, b1, a1, a2 = (1 - c) / 2 / a0, (1 - c) / a0, -2 * c / a0, (1 - al) / a0
    p("/* bot B's low-pass (1400 Hz, Q 1 dB): y = b0 x + b1 x1 + b0 x2 - a1 y1 - a2 y2, Q30 */\n")
    p(f"#define LP_B0 {q(b0)}\n#define LP_B1 {q(b1)}\n#define LP_A1 ({q(a1)})\n#define LP_A2 {q(a2)}\n\n")

    # the reverb
    ir = fdn_ir(int(1.3 * SR))
    scale = math.sqrt(ENERGY / float((ir ** 2).sum()))
    p(f"/* the hall reverb: tau {TAU:.1f} samples, energy {ENERGY:.5f}; the input x {scale:.5f} (Q24) */\n")
    p(f"#define REV_PRE {PRE}\n#define REV_IN {q(scale, 24)}\n#define REV_DIRECT {q(DIRECT, 15)}\n")
    p(f"#define AP_G4 {q(1 - AP_G, 32)}          /* 1 - the all-passes' 0.6, Q32: x 0.6 = x - (x 0.4) */\n")
    p(f"#define REV_LINES_TOTAL {sum(LINES)}\n#define REV_APS_TOTAL {sum(APS)}\n")
    p("/* the lines' and all-passes' lengths and where each starts in its buffer; each line's gain\n"
      " * exp(-length / tau) / sqrt(8) (the Hadamard's scale with it), Q32 */\n")
    for i, d in enumerate(LINES):
        p(f"#define REV_L{i} {d}\n#define REV_O{i} {sum(LINES[:i])}\n"
          f"#define REV_K{i} {q(math.exp(-d / TAU) / math.sqrt(8), 32)}\n")
    for i, d in enumerate(APS):
        p(f"#define AP_L{i} {d}\n#define AP_O{i} {sum(APS[:i])}\n")
    terms = "".join(("+ " if sg > 0 else "- ") + f"r{i} " for i, sg in enumerate(SIGNS))
    p(f"#define REV_TAPS ({terms.lstrip('+ ').strip()})   /* the output: the lines with their signs */\n")
    p("\n")

    # the limiter
    cv = Curve()
    makeup = (1.0 / cv.saturate(1.0)) ** 0.6
    sat_frames = SAT_RELEASE * SR
    p("/* the limiter: Chromium's DynamicsCompressorKernel as Tone.Limiter(-6) sets it (compressor.py) */\n")
    p(f"#define LIM_PRE {int(PRE_DELAY * SR)}\n#define LIM_MAKEUP {q(makeup)}\n")
    p(f"#define LIM_THRESH {int(math.ceil(cv.linear_threshold * 32768))}   /* |x| (Q15) from here on is compressed */\n")
    r0 = 10 ** (2.0 / 20 / sat_frames) - 1
    p(f"#define LIM_R0 {q(r0)}                      /* the detector's release under the threshold */\n")
    att, satr = [], []
    for i in range(6 * 64 + 1):                         # |x| = 2^(14 + i / 64), 0.5 .. 32
        e, m = 14 + i // 64, i % 64
        a = ((1 << e) + m * (1 << (e - 6))) / 32768.0
        at = 1.0 if a <= 0.0001 else cv.saturate(a) / a
        at_db = max(2.0, -20 * math.log10(at))
        att.append(q(min(at, 1.0)))
        satr.append(q(10 ** (at_db / 20 / sat_frames) - 1))
    p("/* the detector's attenuation and release rate by |x| (Q15): index (e - 14) * 64 + the next 6 bits */\n")
    p(table("LIM_ATT", "int32_t", att, 6))
    p(table("LIM_SATR", "int32_t", satr, 6))
    p("/* asin(1 - s^2) / (pi / 2) for s = 0 .. 1 in 256 steps (the detector's gain, warped), Q30 */\n")
    p(table("LIM_ASIN", "int32_t", [q(math.asin(1 - (i / 256) ** 2) / (math.pi / 2)) for i in range(257)], 6))
    p("/* sin(pi / 2 x) for x = 0 .. 1 in 256 steps (the gain, unwarped), Q30 */\n")
    p(table("LIM_SIN", "int32_t", [q(math.sin(math.pi / 2 * i / 256)) for i in range(257)], 6))
    rf = 0.01 * SR
    y1, y2, y3, y4 = (rf * z for z in ZONES)
    kA = 0.9999999999999998 * y1 + 1.8432219684323923e-16 * y2 - 1.9373394351676423e-16 * y3 + 8.824516011816245e-18 * y4
    kB = -1.5788320352845888 * y1 + 2.3305837032074286 * y2 - 0.9141194204840429 * y3 + 0.1623677525612032 * y4
    kC = 0.5334142869106424 * y1 - 1.272736789213631 * y2 + 0.9258856042207512 * y3 - 0.18656310191776226 * y4
    kD = 0.08783463138207234 * y1 - 0.1694162967925622 * y2 + 0.08588057951595272 * y3 - 0.00429891410546283 * y4
    kE = -0.042416883008123074 * y1 + 0.1115693827987602 * y2 - 0.09764676325265872 * y3 + 0.028494263462021576 * y4
    rel = []
    for i in range(97):                                 # the gain's difference -12 .. 0 dB in 1/8 dB
        t = 0.25 * (i / 8.0)
        frames = kA + kB * t + kC * t * t + kD * t ** 3 + kE * t ** 4
        rel.append(q(10 ** (SPACING_DB / frames / 20)))
    p("/* the adaptive release: the gain's rate a frame by its difference -12 .. 0 dB in 1/8 dB, Q30 */\n")
    p(table("LIM_REL", "int32_t", rel, 6))
    atk = []
    for i in range(256):                                # the largest difference 0.5 .. 32.375 dB in 1/8 dB
        eff = 0.5 + i / 8.0
        atk.append(q(1 - (0.25 / eff) ** (1 / (0.003 * SR))))
    p("/* the attack: the gain's rate a frame by the largest difference since the release, 0.5 dB on in 1/8 dB, Q30 */\n")
    p(table("LIM_ATK", "int32_t", atk, 6))
    p("/* log2(1 + i / 64), Q16 */\n")
    p(table("LOG2_FRAC", "int32_t", [q(math.log2(1 + i / 64), 16) for i in range(65)], 8))
    p("\n#endif\n")
    return "".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is not what tools/tone-ref/mix_tables.py writes")
            sys.exit(1)
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
