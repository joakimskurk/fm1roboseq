#!/usr/bin/env python3
"""RoboSeq's splash (firmware/src/rs_splash.c animates it): the RoboSeq lettering as pixel art, 7 x 11 a letter on a
grid of 3 px, written out as firmware/src/rs_splash_art.h. After the product owner's draft (2026-11-06): mint
letters, lit on top, an outline. A preview of the lettering at 4x in build/art/logo.png.

  python3 tools/art/splash.py [--check]"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LETTERS = {
    "R": ["######.", "##...##", "##...##", "##...##", "######.", "##.##..", "##..##.", "##...##", "##...##",
          ".......", "......."],
    "o": [".......", ".......", ".......", ".#####.", "##...##", "##...##", "##...##", "##...##", ".#####.",
          ".......", "......."],
    "b": ["##.....", "##.....", "##.....", "######.", "##...##", "##...##", "##...##", "##...##", "######.",
          ".......", "......."],
    "S": [".#####.", "##...##", "##.....", "###....", ".#####.", "....###", ".....##", "##...##", ".#####.",
          ".......", "......."],
    "e": [".......", ".......", ".......", ".#####.", "##...##", "#######", "##.....", "##...##", ".#####.",
          ".......", "......."],
    "q": [".......", ".......", ".......", ".######", "##...##", "##...##", "##...##", "##...##", ".######",
          ".....##", ".....##"],
}
WORD = "RoboSeq"


def letter(ch):
    """a letter's grid, its pixels lit on top ('h'), the body ('a'), shaded at its foot ('n')"""
    g = [list(r) for r in LETTERS[ch]]
    on = lambda x, y: 0 <= y < 11 and 0 <= x < 7 and LETTERS[ch][y][x] == "#"
    for y in range(11):
        for x in range(7):
            if on(x, y):
                g[y][x] = "h" if not on(x, y - 1) else "n" if not on(x, y + 1) else "a"
    return ["".join(r) for r in g]


def header():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */\n",
           "/* Generated by tools/art/splash.py: the RoboSeq lettering, 7 x 11 a letter ('h' lit, 'a', 'n' shaded). */\n",
           f"static const char LOGO[{len(WORD)}][11][8] = {{\n"]
    out.append(",\n".join("    {" + ", ".join(f'"{r}"' for r in letter(c)) + "}" for c in WORD))
    out.append("};\n")
    return "".join(out)


def preview(path):
    from PIL import Image
    col = {"h": (0xd6, 0xff, 0xf0), "a": (0x8f, 0xff, 0xd1), "n": (0x3c, 0xb8, 0x96)}
    img = Image.new("RGB", (len(WORD) * 24 + 8, 41), (0x0d, 0x2a, 0x2a))
    for i, c in enumerate(WORD):
        g = letter(c)
        for y in range(11):
            for x in range(7):
                if g[y][x] in col:
                    for d in range(9):
                        img.putpixel((4 + i * 24 + x * 3 + d % 3, 4 + y * 3 + d // 3), col[g[y][x]])
    path.parent.mkdir(parents=True, exist_ok=True)
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(path)


if __name__ == "__main__":
    out = ROOT / "firmware" / "src" / "rs_splash_art.h"
    if "--check" in sys.argv:
        sys.exit(0 if out.read_text() == header() else "firmware/src/rs_splash_art.h is not what tools/art/splash.py writes")
    out.write_text(header())
    preview(ROOT / "build" / "art" / "logo.png")
    print("wrote", out.relative_to(ROOT), "and build/art/logo.png")
