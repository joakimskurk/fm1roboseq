"""RoboSeq's robots, Scout-7 and Echo-3, as pixel art at 1 px: 18 x 18, as the board draws them, each always on its own
side of a tile (D17), and 32 x 32 as the splash draws them (twice the size). After
the HTML's robotPixelArt (the same build, the same colours), with what 1 px gives room for: a dark outline, light
from straight above (each part lit on top, shaded at its foot), the grill, the joints; left and right mirror
images of each other, as the HTML's are.
Written out as firmware/src/rs_robots.h, a preview at 6x in build/art/robots.png.

Letters (rs_screen.c bot_colour): '.' nothing, 'o' outline, 'm' the bot's colour, 'M' it lit, 'n' it shaded,
'd' its dark colour, 'a' its accent, 'v' the visor, 'w' white, 't' the thrusters' glow.

  python3 tools/art/robots.py [--check]"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
N = 32
COMMON = [  # x, y, w, h, letter: robotPixelArt's rects, both bots
    (10, 4, 12, 2, "m"), (8, 6, 16, 10, "m"), (9, 8, 14, 6, "v"),
    (10, 9, 4, 4, "a"), (12, 10, 2, 2, "w"), (18, 9, 4, 4, "a"), (18, 10, 2, 2, "w"),
    (13, 14, 6, 1, "d"), (6, 8, 2, 4, "d"), (24, 8, 2, 4, "d"), (11, 16, 10, 6, "m"),
    (14, 17, 4, 2, "a"), (8, 17, 3, 4, "d"), (7, 21, 3, 2, "a"), (21, 17, 3, 4, "d"),
    (22, 21, 3, 2, "a"), (12, 22, 3, 4, "d"), (17, 22, 3, 4, "d"), (11, 26, 4, 2, "m"),
    (17, 26, 4, 2, "m"), (12, 28, 2, 2, "t"), (18, 28, 2, 2, "t")]
ANTENNA = {"A": [(15, 0, 2, 2, "a"), (15, 2, 2, 2, "d")],
           "B": [(9, 0, 2, 2, "a"), (21, 0, 2, 2, "a"), (10, 2, 2, 2, "d"), (20, 2, 2, 2, "d")]}
# the small ones, 18 x 18, for two on one tile (side by side, fighting or in love): the same build, drawn small
M = 18
MINI = [
    (5, 2, 8, 1, "m"), (4, 3, 10, 6, "m"), (5, 4, 8, 4, "v"), (6, 5, 2, 2, "a"), (10, 5, 2, 2, "a"),
    (7, 5, 1, 1, "w"), (10, 5, 1, 1, "w"), (7, 8, 4, 1, "d"), (3, 5, 1, 2, "d"), (14, 5, 1, 2, "d"),
    (5, 9, 8, 4, "m"), (8, 10, 2, 1, "a"), (3, 9, 2, 3, "d"), (13, 9, 2, 3, "d"), (3, 12, 2, 1, "a"),
    (13, 12, 2, 1, "a"), (6, 13, 2, 3, "d"), (10, 13, 2, 3, "d"), (5, 16, 3, 1, "m"), (10, 16, 3, 1, "m"),
    (6, 17, 2, 1, "t"), (10, 17, 2, 1, "t")]
MINI_ANTENNA = {"A": [(8, 0, 2, 1, "a"), (8, 1, 2, 1, "d")],
                "B": [(4, 0, 1, 1, "a"), (13, 0, 1, 1, "a"), (5, 1, 1, 1, "d"), (12, 1, 1, 1, "d")]}


def robot(b, mini=False):
    n = M if mini else N
    g = [["."] * n for _ in range(n)]
    for (x0, y0, w, h, ch) in (MINI_ANTENNA[b] + MINI if mini else ANTENNA[b] + COMMON):
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                g[y][x] = ch
    solid = lambda x, y: 0 <= x < n and 0 <= y < n and g[y][x] not in ".o"
    body = [[g[y][x] for x in range(n)] for y in range(n)]
    for y in range(n):                              # the light, from above: lit on top, shaded at the foot
        for x in range(n):
            c = body[y][x]
            if c != "m":
                continue
            up = y > 0 and body[y - 1][x] in "mMn"
            left = x > 0 and body[y][x - 1] in "mMn"
            down = y < n - 1 and body[y + 1][x] in "mMn"
            if not up:
                g[y][x] = "M"
            elif not down:
                g[y][x] = "n"
    if not mini:
        for x in (14, 17):                          # the grill: slots in the mouth
            g[14][x] = "v"
        for (x, y) in [(15, 20), (16, 20)]:         # a seam under the core
            g[y][x] = "n"
        for (x, y) in [(13, 24), (18, 24)]:         # knees
            g[y][x] = "a"
    for y in range(n):                              # the outline
        for x in range(n):
            if g[y][x] == "." and any(solid(x + dx, y + dy) for dx, dy in [(1, 0), (-1, 0), (0, 1), (0, -1)]):
                g[y][x] = "o"
    return g


BOTS = {"A": robot("A"), "B": robot("B")}
MINIS = {"A": robot("A", True), "B": robot("B", True)}


def header():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */\n/* Copyright (C) 2026 Joakim (joakimskurk) */\n",
           "/* Generated by tools/art/robots.py: Scout-7 and Echo-3, 32 x 32 (the splash) and 18 x 18 (the board). */\n"]
    for k, g in BOTS.items():                       # (the splash's, drawn twice the size)
        out.append(f"static const char ART_BOT_{k}[{N}][{N + 1}] = {{\n" + ",\n".join(f'    "{"".join(r)}"' for r in g) + "};\n")
    for k, g in MINIS.items():
        out.append(f"static const char ART_MINI_{k}[{M}][{M + 1}] = {{\n" + ",\n".join(f'    "{"".join(r)}"' for r in g) + "};\n")
    return "".join(out)


def preview(path):
    from PIL import Image
    hx = lambda h: tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
    mix = lambda a, b, t: tuple(int(a[i] * t + b[i] * (1 - t)) for i in range(3))
    under = hx("#0c0c18")
    def pal(main, dark, acc):
        m, d, a = hx(main), hx(dark), hx(acc)
        return {".": under, "o": hx("#05050c"), "m": m, "M": mix((255, 255, 255), m, .35), "n": mix(m, d, .5), "d": d,
                "a": a, "v": hx("#0a0a1a"), "w": (255, 255, 255), "t": mix(a, under, .6)}
    P = {"A": pal("#ff6666", "#cc3333", "#8fffd1"), "B": pal("#ff9900", "#cc7700", "#ffcc00")}
    img = Image.new("RGB", (2 * (N + 8) + 44, N + 8), under)
    for i, (k, g) in enumerate(BOTS.items()):
        for y in range(N):
            for x in range(N):
                img.putpixel((4 + i * (N + 8) + x, 4 + y), P[k][g[y][x]])
    for i, (k, g) in enumerate(MINIS.items()):     # the two small ones together, as on one tile
        for y in range(M):
            for x in range(M):
                if g[y][x] != ".":
                    img.putpixel((2 * (N + 8) + 2 + i * 18 + x, 4 + 14 + y), P[k][g[y][x]])
    path.parent.mkdir(parents=True, exist_ok=True)
    img.resize((img.width * 6, img.height * 6), Image.NEAREST).save(path)


if __name__ == "__main__":
    out = ROOT / "firmware" / "src" / "rs_robots.h"
    if "--check" in sys.argv:
        sys.exit(0 if out.read_text() == header() else "firmware/src/rs_robots.h is not what tools/art/robots.py writes")
    out.write_text(header())
    preview(ROOT / "build" / "art" / "robots.png")
    print("wrote", out.relative_to(ROOT), "and build/art/robots.png")
